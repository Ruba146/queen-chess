require('dotenv').config();
const { PrismaClient } = require('@prisma/client');
const { PrismaPg } = require('@prisma/adapter-pg');

const prisma = new PrismaClient({
  adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }),
  log: ['error'],
});

async function main() {
  try {
    await prisma.$connect();
    console.log('Database connected\n');

    const { generateAIPuzzle } = require('./src/services/stockfishPuzzleGenerator');
    
    console.log('Attempting dynamic puzzle generation for tactics...');
    const puzzle = await generateAIPuzzle('tactics', null, []);
    
    if (puzzle) {
      console.log('SUCCESS: Dynamic puzzle generated!');
      console.log('FEN:', puzzle.fen);
      console.log('Solution:', puzzle.solution);
      console.log('Theme:', puzzle.theme);
      console.log('Category:', puzzle.category);
      console.log('Rating:', puzzle.rating);
      console.log('Goal:', puzzle.goal);
      console.log('Generated by AI:', puzzle.generatedByAI);
      console.log('Is new:', puzzle.isNew);
    } else {
      console.log('FAILED: No puzzle generated');
    }
  } catch (err) {
    console.error('Error:', err.message);
    console.error(err.stack);
  } finally {
    await prisma.$disconnect();
  }
}

main();
